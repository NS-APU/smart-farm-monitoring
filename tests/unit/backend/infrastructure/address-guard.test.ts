/**
 * 接続先（ホスト・IP アドレス）の制限の判定（Issue #172。ADR-0022）の単体テスト。
 * 管理者が接続先を設定できるため、Lambda から、内部のアドレス（ループバック・プライベート・リンクローカル。
 * AWS のメタデータの 169.254.169.254 を含む）へ、リクエストを送れないようにする（SSRF の対策）。
 */

import { describe, expect, it } from 'vitest';
import {
  isBlockedConnectionHost,
  isBlockedHostname,
  isBlockedIpAddress,
} from '../../../../src/backend/infrastructure/http/address-guard.ts';

describe('拒否する IP アドレス（IPv4）', () => {
  it.each([
    ['ループバック', '127.0.0.1'],
    ['ループバックの範囲', '127.255.255.254'],
    ['この（0.0.0.0/8）', '0.0.0.0'],
    ['プライベート 10/8', '10.0.0.1'],
    ['プライベート 172.16/12 の下端', '172.16.0.1'],
    ['プライベート 172.16/12 の上端', '172.31.255.255'],
    ['プライベート 192.168/16', '192.168.1.10'],
    ['リンクローカル（AWS のメタデータ）', '169.254.169.254'],
    ['リンクローカルの範囲', '169.254.0.1'],
    ['キャリアグレード NAT 100.64/10', '100.64.0.1'],
    ['キャリアグレード NAT の上端', '100.127.255.255'],
    ['プロトコル用 192.0.0.0/24', '192.0.0.1'],
    ['ドキュメント用 192.0.2.0/24', '192.0.2.1'],
    ['ドキュメント用 198.51.100.0/24', '198.51.100.1'],
    ['ドキュメント用 203.0.113.0/24', '203.0.113.1'],
    ['ベンチマーク用 198.18.0.0/15', '198.19.255.255'],
    ['マルチキャスト', '224.0.0.1'],
    ['予約済み 240/4', '240.0.0.1'],
    ['ブロードキャスト', '255.255.255.255'],
  ])('%s（%s）は、拒否する', (_name, address) => {
    expect(isBlockedIpAddress(address)).toBe(true);
  });

  it.each([
    ['公開のアドレス', '8.8.8.8'],
    ['公開のアドレス（172.15 は、プライベートではない）', '172.15.255.255'],
    ['公開のアドレス（172.32 は、プライベートではない）', '172.32.0.1'],
    ['公開のアドレス（100.63 は、100.64/10 の外）', '100.63.255.255'],
    ['公開のアドレス（100.128 は、100.64/10 の外）', '100.128.0.1'],
    ['公開のアドレス（198.17 は、198.18/15 の外）', '198.17.255.255'],
    ['公開のアドレス（169.253）', '169.253.1.1'],
    ['公開のアドレス（223.255.255.255）', '223.255.255.255'],
  ])('%s（%s）は、許可する', (_name, address) => {
    expect(isBlockedIpAddress(address)).toBe(false);
  });
});

describe('拒否する IP アドレス（IPv6）', () => {
  it.each([
    ['ループバック', '::1'],
    ['未指定', '::'],
    ['ユニークローカル fc00::/7', 'fd12:3456:789a::1'],
    ['ユニークローカルの下端', 'fc00::1'],
    ['リンクローカル fe80::/10', 'fe80::1'],
    ['リンクローカルの上端', 'febf::1'],
    ['マルチキャスト ff00::/8', 'ff02::1'],
    ['IPv4 マッピング（ループバック）', '::ffff:127.0.0.1'],
    ['IPv4 マッピング（プライベート）', '::ffff:10.0.0.1'],
    ['IPv4 マッピング（メタデータ）', '::ffff:169.254.169.254'],
    ['IPv4 マッピング（16 進の表記）', '::ffff:7f00:1'],
    ['ドキュメント用 2001:db8::/32', '2001:db8::1'],
    ['IPv4 互換（ループバック）', '::127.0.0.1'],
    ['大文字', 'FE80::ABCD'],
    ['サイトローカル fec0::/10（廃止された範囲。内部の可能性があるため、拒否）', 'fec0::1'],
    ['NAT64（IPv4 に変換される。埋め込まれた IPv4 が、プライベート）', '64:ff9b::a00:1'],
    ['6to4（埋め込まれた IPv4 が、ループバック）', '2002:7f00:1::1'],
  ])('%s（%s）は、拒否する', (_name, address) => {
    expect(isBlockedIpAddress(address)).toBe(true);
  });

  it.each([
    ['公開のアドレス', '2606:4700:4700::1111'],
    ['公開のアドレス（2001:4860）', '2001:4860:4860::8888'],
    ['IPv4 マッピング（公開）', '::ffff:8.8.8.8'],
    ['NAT64（埋め込まれた IPv4 が、公開）', '64:ff9b::808:808'],
  ])('%s（%s）は、許可する', (_name, address) => {
    expect(isBlockedIpAddress(address)).toBe(false);
  });
});

describe('IP アドレスとして読めない値', () => {
  it.each(['', 'example.com', '256.1.1.1', '1.2.3', '1.2.3.4.5', '::g', ':::', '12345::1'])(
    '%s は、拒否する（判定できない値は、安全側に倒す）',
    (value) => {
      expect(isBlockedIpAddress(value)).toBe(true);
    },
  );
});

describe('拒否するホスト名', () => {
  it.each([
    'localhost',
    'LOCALHOST',
    'foo.localhost',
    'localhost.',
    'metadata.google.internal',
    'service.internal',
    'printer.local',
    'host.lan',
    'router.home.arpa',
    'broadcasthost',
    'ip6-localhost',
    'ip6-loopback',
    // 数字だけ・16 進の表記の名前は、名前の解決で、IP アドレスとして解釈される（127.0.0.1 など）ため、拒否する
    '2130706433',
    '127.1',
    '0x7f.0.0.1',
    '0177.0.0.1',
  ])('%s は、拒否する', (host) => {
    expect(isBlockedHostname(host)).toBe(true);
  });

  it.each([
    'fileserver.example.ac.jp',
    'files.example.com',
    'internal-files.example.com',
    'a.b.c.d',
  ])('%s は、許可する（名前の解決後の IP アドレスで、あらためて検査する）', (host) => {
    expect(isBlockedHostname(host)).toBe(false);
  });
});

describe('接続設定のホスト（IP アドレス・[IPv6]・名前）の判定', () => {
  it.each([
    '127.0.0.1',
    '10.0.0.1',
    '169.254.169.254',
    '[::1]',
    '[fd00::1]',
    'localhost',
    'files.internal',
    '2130706433',
  ])('%s は、拒否する', (host) => {
    expect(isBlockedConnectionHost(host)).toBe(true);
  });

  it.each(['8.8.8.8', '[2606:4700:4700::1111]', 'fileserver.example.ac.jp', 'files'])(
    '%s は、許可する',
    (host) => {
      expect(isBlockedConnectionHost(host)).toBe(false);
    },
  );
});
